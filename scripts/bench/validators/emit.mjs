// Emit one TypeScript module per validator flavor from a neutral descriptor.
// Every module declares each schema as `export const <name> = …` in descriptor
// order and exports `forceNative()`, which builds the native Convex validator
// of every schema plus one `defineTable` and one `queryGeneric` per group.
import { validate } from './descriptor.mjs'

export const flavors = ['zod', 'zod-mini', 'convex', 'k']

/**
 * Returns the TypeScript source of `descriptor` written with `flavor`.
 * `kSpecifier` is the import specifier of the `k` entry (only used by `k`).
 */
export function emit(descriptor, flavor, kSpecifier = 'cvx-kit/k') {
	validate(descriptor)
	const writer = writers[flavor]
	if (!writer) throw new Error(`Unknown flavor ${JSON.stringify(flavor)}`)
	const lines = [
		'// Generated by scripts/bench/validators/emit.mjs. Do not edit.',
		...writer.header(kSpecifier),
		"import { defineTable, queryGeneric } from 'convex/server'",
		'',
	]
	for (const { name, node } of descriptor.schemas)
		lines.push(`export const ${name} = ${write(writer, node)}`)
	const index = new Map(descriptor.schemas.map(({ name }, position) => [name, position]))
	lines.push(
		'',
		'export function forceNative() {',
		...descriptor.schemas.map(
			({ name }, position) => `\tconst native${position} = ${writer.native(name)}`,
		),
		'\treturn {',
		`\t\tvalidators: [${descriptor.schemas.map((_, position) => `native${position}`).join(', ')}],`,
		'\t\ttables: [',
		...(descriptor.groups ?? []).map(
			(group) => `\t\t\tdefineTable(native${index.get(group.table)}),`,
		),
		'\t\t],',
		'\t\tqueries: [',
		...(descriptor.groups ?? []).map(
			(group) =>
				`\t\t\tqueryGeneric({ args: native${index.get(group.args)}, handler: async () => null }),`,
		),
		'\t\t],',
		'\t}',
		'}',
		'',
	)
	return lines.join('\n')
}

function write(writer, node) {
	return writer.wrap(
		writer.node(node, (child) => write(writer, child)),
		node,
	)
}

const json = (value) => JSON.stringify(value)

/** A regex literal for `source`, escaping the characters a literal cannot hold. */
export function regexLiteral(source) {
	let out = ''
	for (let index = 0; index < source.length; index++) {
		const char = source[index]
		if (char === '\\') {
			out += char + (source[index + 1] ?? '\\')
			index++
		} else if (char === '/') out += '\\/'
		else if (char === '\n') out += '\\n'
		else if (char === '\r') out += '\\r'
		else out += char
	}
	return `/${out || '(?:)'}/`
}

const fields = (node, child) =>
	`{ ${Object.entries(node.fields ?? {})
		.map(([key, value]) => `${key}: ${child(value)}`)
		.join(', ')} }`

/** Classic Zod chain: normalisers and checks in descriptor order (trim first). */
function zodChecks(node) {
	let out = ''
	if (node.trim) out += '.trim()'
	if (node.min !== undefined) out += `.min(${node.min})`
	if (node.max !== undefined) out += `.max(${node.max})`
	if (node.regex !== undefined) out += `.regex(${regexLiteral(node.regex)})`
	return out
}

function miniChecks(node) {
	const lengthy = node.kind === 'string' || node.kind === 'array'
	const checks = []
	if (node.trim) checks.push('z.trim()')
	if (node.min !== undefined)
		checks.push(lengthy ? `z.minLength(${node.min})` : `z.gte(${node.min})`)
	if (node.max !== undefined)
		checks.push(lengthy ? `z.maxLength(${node.max})` : `z.lte(${node.max})`)
	if (node.regex !== undefined) checks.push(`z.regex(${regexLiteral(node.regex)})`)
	return checks.length ? `.check(${checks.join(', ')})` : ''
}

const writers = {
	zod: {
		header: () => [
			"import { z } from 'zod'",
			"import { zid, zodToConvex } from 'convex-helpers/server/zod4'",
		],
		native: (name) => `zodToConvex(${name})`,
		node(node, child) {
			switch (node.kind) {
				case 'string':
					return `z.string()${zodChecks(node)}`
				case 'number':
					return `z.number()${zodChecks(node)}`
				case 'int':
					return `z.int()${zodChecks(node)}`
				case 'boolean':
					return 'z.boolean()'
				case 'null':
					return 'z.null()'
				case 'literal':
					return `z.literal(${json(node.value)})`
				case 'enum':
					return `z.enum(${json(node.values)})`
				case 'id':
					return `zid(${json(node.table)})`
				case 'array':
					return `z.array(${child(node.element)})${zodChecks(node)}`
				case 'object':
					return `z.strictObject(${fields(node, child)})`
				case 'union':
					return `z.union([${node.members.map(child).join(', ')}])`
				default:
					return node.name
			}
		},
		wrap(expr, node) {
			let out = expr
			if (node.nullable) out += '.nullable()'
			if (node.default !== undefined) out += `.default(${json(node.default)})`
			else if (node.optional) out += '.optional()'
			return out
		},
	},
	'zod-mini': {
		header: () => [
			"import * as z from 'zod/mini'",
			// convex-helpers' zid is built on classic Zod, so this flavor bundles
			// classic Zod as well; that is what a zod/mini app gets today.
			"import { zid, zodToConvex } from 'convex-helpers/server/zod4'",
		],
		native: (name) => `zodToConvex(${name})`,
		node(node, child) {
			switch (node.kind) {
				case 'string':
					return `z.string()${miniChecks(node)}`
				case 'number':
					return `z.number()${miniChecks(node)}`
				case 'int':
					return `z.int()${miniChecks(node)}`
				case 'boolean':
					return 'z.boolean()'
				case 'null':
					return 'z.null()'
				case 'literal':
					return `z.literal(${json(node.value)})`
				case 'enum':
					return `z.enum(${json(node.values)})`
				case 'id':
					return `zid(${json(node.table)})`
				case 'array':
					return `z.array(${child(node.element)})${miniChecks(node)}`
				case 'object':
					return `z.strictObject(${fields(node, child)})`
				case 'union':
					return `z.union([${node.members.map(child).join(', ')}])`
				default:
					return node.name
			}
		},
		wrap(expr, node) {
			let out = expr
			if (node.nullable) out = `z.nullable(${out})`
			if (node.default !== undefined) out = `z._default(${out}, ${json(node.default)})`
			else if (node.optional) out = `z.optional(${out})`
			return out
		},
	},
	convex: {
		header: () => [
			// Plain validators cannot express checks or defaults; both are dropped
			// (a default becomes v.optional).
			"import { v } from 'convex/values'",
		],
		native: (name) => name,
		node(node, child) {
			switch (node.kind) {
				case 'string':
					return 'v.string()'
				case 'number':
				case 'int':
					return 'v.number()'
				case 'boolean':
					return 'v.boolean()'
				case 'null':
					return 'v.null()'
				case 'literal':
					return `v.literal(${json(node.value)})`
				case 'enum':
					return `v.union(${node.values.map((value) => `v.literal(${json(value)})`).join(', ')})`
				case 'id':
					return `v.id(${json(node.table)})`
				case 'array':
					return `v.array(${child(node.element)})`
				case 'object':
					return `v.object(${fields(node, child)})`
				case 'union':
					return `v.union(${node.members.map(child).join(', ')})`
				default:
					return node.name
			}
		},
		wrap(expr, node) {
			let out = expr
			if (node.nullable) out = `v.union(${out}, v.null())`
			if (node.optional || node.default !== undefined) out = `v.optional(${out})`
			return out
		},
	},
	k: {
		header: (kSpecifier) => [`import { k } from ${json(kSpecifier)}`],
		native: (name) => `${name}.validator`,
		node(node, child) {
			switch (node.kind) {
				case 'string':
					return `k.string()${zodChecks(node)}`
				case 'number':
					return `k.number()${zodChecks(node)}`
				case 'int':
					return `k.int()${zodChecks(node)}`
				case 'boolean':
					return 'k.boolean()'
				case 'null':
					return 'k.null()'
				case 'literal':
					return `k.literal(${json(node.value)})`
				case 'enum':
					return `k.enum(${json(node.values)})`
				case 'id':
					return `k.id(${json(node.table)})`
				case 'array':
					return `k.array(${child(node.element)})${zodChecks(node)}`
				case 'object':
					return `k.object(${fields(node, child)})`
				case 'union':
					return `k.union([${node.members.map(child).join(', ')}])`
				default:
					return node.name
			}
		},
		wrap(expr, node) {
			let out = expr
			if (node.nullable) out += '.nullable()'
			if (node.default !== undefined) out += `.default(${json(node.default)})`
			else if (node.optional) out += '.optional()'
			return out
		},
	},
}
