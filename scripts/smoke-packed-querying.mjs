async function run(label, args) {
	commands.push([process.execPath, 'node_modules/convex/bin/main.js', ...args])
	writeFileSync(join(fixture, 'commands.json'), JSON.stringify(commands, null, 2))
	const result = await runOwnedProcess({
		command: process.execPath,
		args: commands.at(-1).slice(1),
		cwd: fixture,
		env,
		onSpawn: (pid) => processes.push(pid),
	})
	const { stdout, stderr, ...evidence } = result
	writeFileSync(join(fixture, label + '.stdout.log'), stdout)
	writeFileSync(join(fixture, label + '.stderr.log'), stderr)
	writeFileSync(join(fixture, label + '-result.json'), JSON.stringify(evidence, null, 2))
	assert.equal(result.code, 0, label + ' failed; retained logs')
	assert.equal(result.timedOut, false, label + ' timed out; retained logs')
	assert.equal(result.cleanup?.alive, false, label + ' owned group survived cleanup')
	console.log(label + ': exit 0')
}
