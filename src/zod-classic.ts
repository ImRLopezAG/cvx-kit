/** Classic Zod conversion using named constructors so unused exports can be removed. */
import {
	string,
	number,
	int,
	bigint,
	boolean,
	null as nullType,
	undefined as undefinedType,
	instanceof as instanceOf,
	any,
	json,
	record,
	literal,
	enum as enumType,
	array,
	object,
	looseObject,
	strictObject,
	union,
	discriminatedUnion,
	optional,
	nullable,
	prefault,
	_default,
	describe,
	gte,
	lte,
	gt,
	lt,
	minLength,
	maxLength,
	length,
	regex,
	refine,
	trim,
	toLowerCase,
	toUpperCase,
	check,
	transform,
	pipe,
	iso,
} from 'zod'
import type { KType } from './k/types'
import { toZodWithFactory, type KClassicZod } from './zod'

/** Convert a kit schema to classic Zod 4, preserving input/output types and chain methods. */
export function toZod<S extends KType>(schema: S): KClassicZod<S> {
	return toZodWithFactory(schema, classicFunctions)
}

const classicFunctions = {
	string,
	number,
	int,
	bigint,
	boolean,
	null: nullType,
	undefined: undefinedType,
	instanceof: instanceOf,
	any,
	json,
	record,
	literal,
	enum: enumType,
	array,
	object,
	looseObject,
	strictObject,
	union,
	discriminatedUnion,
	optional,
	nullable,
	prefault,
	_default,
	describe,
	iso: { date: iso.date, datetime: iso.datetime },
	gte,
	lte,
	gt,
	lt,
	minLength,
	maxLength,
	length,
	regex,
	refine,
	trim,
	toLowerCase,
	toUpperCase,
	check,
	transform,
	pipe,
}
