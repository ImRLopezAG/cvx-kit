// @vitest-environment node
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { afterAll, describe, expect, it } from 'vite-plus/test'
import { bundle } from '../scripts/bench-validators.mjs'
import { validate } from '../scripts/bench/validators/descriptor.mjs'
import { emit } from '../scripts/bench/validators/emit.mjs'
import { synthetic } from '../scripts/bench/validators/synthetic.mjs'

const every = {
	schemas: [
		{ name: 'status', node: { kind: 'enum', values: ['open', 'closed'] } },
		{
			name: 'item',
			node: {
				kind: 'object',
				fields: {
					label: { kind: 'string', trim: true, min: 1, max: 80, regex: '^[a-z/]+$' },
					count: { kind: 'int', min: 0, max: 10, default: 0 },
					price: { kind: 'number', min: 0, nullable: true },
					done: { kind: 'boolean', optional: true },
				},
			},
		},
		{
			name: 'order',
			node: {
				kind: 'object',
				fields: {
					owner: { kind: 'id', table: 'users' },
					status: { kind: 'ref', name: 'status', default: 'open' },
					items: { kind: 'array', element: { kind: 'ref', name: 'item' }, min: 1, max: 5 },
					note: { kind: 'string', nullable: true, optional: true },
					meta: {
						kind: 'object',
						fields: { tag: { kind: 'string', max: 12 } },
						optional: true,
					},
					source: {
						kind: 'union',
						members: [
							{ kind: 'literal', value: 'web' },
							{ kind: 'literal', value: 2 },
							{ kind: 'null' },
						],
					},
					flag: { kind: 'literal', value: true },
					cleared: { kind: 'null' },
				},
			},
		},
		{
			name: 'orderArgs',
			node: { kind: 'object', fields: { id: { kind: 'id', table: 'orders' } } },
		},
	],
	groups: [{ name: 'orders', table: 'order', args: 'orderArgs' }],
}

const dir = mkdtempSync(join(tmpdir(), 'cvx-bench-validators-test-'))
afterAll(() => rmSync(dir, { recursive: true, force: true }))

describe('descriptor', () => {
	it('rejects an unknown kind and names it', () => {
		expect(() =>
			validate({
				schemas: [{ name: 'a', node: { kind: 'object', fields: { b: { kind: 'decimal' } } } }],
			}),
		).toThrow(/"decimal".*a\.b/)
	})

	it('rejects an unknown check and names it', () => {
		expect(() =>
			validate({ schemas: [{ name: 'a', node: { kind: 'number', email: true } }] }),
		).toThrow(/"email"/)
	})
})

describe('emitters', () => {
	it.each(['zod', 'zod-mini', 'convex'])(
		'%s source bundles, evaluates and builds native validators',
		async (flavor) => {
			const out = join(dir, `${flavor}.mjs`)
			const { bytes, packages } = await bundle(emit(every, flavor), out)
			const module = await import(pathToFileURL(out).href)
			for (const { name } of every.schemas) expect(module[name], name).toBeDefined()
			const native = module.forceNative()
			expect(native.validators).toHaveLength(every.schemas.length)
			expect(native.tables).toHaveLength(1)
			expect(native.queries).toHaveLength(1)
			expect(native.validators[2].kind).toBe('object')

			const attributed = Object.entries(packages)
				.filter(([owner]) => owner !== '(glue)')
				.reduce((sum, [, value]) => sum + value, 0)
			expect(attributed).toBeLessThanOrEqual(bytes)
			expect(attributed / bytes).toBeGreaterThan(0.95)
			expect(packages.convex).toBeGreaterThan(0)
			if (flavor === 'convex') expect(packages.zod ?? 0).toBe(0)
			else expect(packages.zod).toBeGreaterThan(0)
		},
	)

	it('emits the expected k source', () => {
		expect(emit(every, 'k', '../src/k/index.ts'))
			.toBe(`// Generated by scripts/bench/validators/emit.mjs. Do not edit.
import { k } from "../src/k/index.ts"
import { defineTable, queryGeneric } from 'convex/server'

export const status = k.enum(["open","closed"])
export const item = k.object({ label: k.string().trim().min(1).max(80).regex(/^[a-z\\/]+$/), count: k.int().min(0).max(10).default(0), price: k.number().min(0).nullable(), done: k.boolean().optional() })
export const order = k.object({ owner: k.id("users"), status: status.default("open"), items: k.array(item).min(1).max(5), note: k.string().nullable().optional(), meta: k.object({ tag: k.string().max(12) }).optional(), source: k.union([k.literal("web"), k.literal(2), k.null()]), flag: k.literal(true), cleared: k.null() })
export const orderArgs = k.object({ id: k.id("orders") })

export function forceNative() {
	const native0 = status.validator
	const native1 = item.validator
	const native2 = order.validator
	const native3 = orderArgs.validator
	return {
		validators: [native0, native1, native2, native3],
		tables: [
			defineTable(native2),
		],
		queries: [
			queryGeneric({ args: native3, handler: async () => null }),
		],
	}
}
`)
	})

	it('emits a nested-field check only in flavors that can express it', () => {
		const nested = {
			schemas: [
				{
					name: 'outer',
					node: {
						kind: 'object',
						fields: { inner: { kind: 'object', fields: { code: { kind: 'string', max: 7 } } } },
					},
				},
			],
		}
		expect(emit(nested, 'zod')).toContain('code: z.string().max(7)')
		expect(emit(nested, 'zod-mini')).toContain('code: z.string().check(z.maxLength(7))')
		expect(emit(nested, 'k')).toContain('code: k.string().max(7)')
		const plain = emit(nested, 'convex')
		expect(plain).toContain('code: v.string()')
		expect(plain).not.toMatch(/7/)
	})
})

describe('synthetic', () => {
	it('is deterministic for a seed and yields the requested schema count', () => {
		const first = synthetic({ schemas: 120, seed: 7 })
		expect(first.schemas).toHaveLength(120)
		expect(synthetic({ schemas: 120, seed: 7 })).toEqual(first)
		expect(synthetic({ schemas: 120, seed: 8 })).not.toEqual(first)
		expect(first.groups.length).toBeGreaterThan(0)
	})
})
